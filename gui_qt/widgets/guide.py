class GuideBanner(QFrame):
    """页面顶部的可折叠使用引导条。

    用法::

        root.addWidget(guide_banner("视频下载"))

    默认展示一行摘要；「详细步骤 ▾」展开分步要点；「✕」在本次会话内收起。
    主题切换时由 MainWindow 统一调用 apply_theme() 刷新图标颜色。
    """

    def __init__(self, key: str, parent=None):
        super().__init__(parent)
        self.setObjectName("GuideBanner")
        self._key = key
        data = GUIDE_CONTENT.get(key, {})
        # ★ 免费版（2026-10-23）：引导条上写着「填授权码 / 激活」这类步骤，
        #   免费版里根本找不到对应入口（授权区已隐藏）。照着点只会让人以为
        #   软件坏了 —— 换成免费版自己该做的事。
        try:
            from justoneapi_collector import branding as _b
            if getattr(_b, "APP_IS_FREE", False):
                data = FREE_GUIDE_OVERRIDES.get(key, data)
        except Exception:                              # noqa: BLE001
            pass
        self._summary = data.get("summary", "本页有操作说明，点击右侧「详细步骤」查看。")
        self._steps = data.get("steps", [])
        self._tips = data.get("tips", [])
        self._build_ui()
        self.apply_theme(_current_mode())

    # ------------------------------------------------------------ 构建
    def _build_ui(self):
        outer = QVBoxLayout(self)
        outer.setContentsMargins(12, 9, 12, 9)
        outer.setSpacing(6)

        head = QHBoxLayout()
        head.setSpacing(8)

        self._icon = QLabel()
        self._icon.setFixedSize(16, 16)
        head.addWidget(self._icon)

        title = QLabel(f"使用提示：{self._summary}")
        title.setObjectName("GuideTitle")
        title.setWordWrap(True)
        head.addWidget(title, 1)

        self._toggle = QPushButton("详细步骤")
        self._toggle.setObjectName("GhostLink")
        self._toggle.setCheckable(True)
        self._toggle.setCursor(Qt.CursorShape.PointingHandCursor)
        self._toggle.setIconSize(QSize(12, 12))
        # 图标排到文字右侧，读起来像「详细步骤 ▾」
        self._toggle.setLayoutDirection(Qt.LayoutDirection.RightToLeft)
        self._toggle.toggled.connect(self._on_toggle)
        head.addWidget(self._toggle)

        close = QPushButton("✕")
        close.setObjectName("GhostIcon")
        close.setFixedSize(22, 22)
        close.setCursor(Qt.CursorShape.PointingHandCursor)
        close.setToolTip("收起本页引导（重新打开软件后恢复）")
        close.clicked.connect(lambda: self.setVisible(False))
        head.addWidget(close)

        outer.addLayout(head)

        self._body = QWidget()
        self._body.setObjectName("GuideBody")
        body = QVBoxLayout(self._body)
        body.setContentsMargins(24, 0, 6, 2)
        body.setSpacing(3)
        for i, step in enumerate(self._steps, 1):
            lab = QLabel(f"{i}. {step}")
            lab.setObjectName("GuideStep")
            lab.setWordWrap(True)
            body.addWidget(lab)
        for tip in self._tips:
            lab = QLabel(f"注意：{tip}")
            lab.setObjectName("GuideTip")
            lab.setWordWrap(True)
            body.addWidget(lab)
        self._body.setVisible(False)
        outer.addWidget(self._body)

    # ------------------------------------------------------------ 行为
    def _on_toggle(self, checked: bool):
        self._body.setVisible(checked)
        self._toggle.setText("收起步骤" if checked else "详细步骤")
        self._toggle.setIcon(chevron_icon(_guide_icon_color(_current_mode()), 12, up=checked))

    def apply_theme(self, mode: str = "light"):
        """主题切换后刷新图标颜色（QSS 负责底色与文字色）。"""
        color = _guide_icon_color(mode)
        self._icon.setPixmap(info_icon(color, 16).pixmap(QSize(16, 16)))
        self._toggle.setIcon(chevron_icon(color, 12, up=self._toggle.isChecked()))

    @property
    def guide_key(self) -> str:
        return self._key


def guide_banner(key: str, parent=None) -> GuideBanner:
    """构造页面引导条的工厂函数（供各页面统一调用）。"""
    return GuideBanner(key, parent)
