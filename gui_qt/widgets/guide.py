def _current_mode() -> str:
    """读取当前主题模式（由 theme.apply_theme 写在 QApplication 属性上）。"""
    app = QApplication.instance()
    if app is None:
        return "light"
    try:
        return app.property("theme_mode") or "light"
    except Exception:  # noqa: BLE001
        return "light"


def _guide_icon_color(mode: str) -> str:
    """引导条图标色。

    引导条底色已改成品牌柠檬浅底（见 light.qss 的 #GuideBanner），
    所以图标不能再沿用旧的"信息蓝"——那块蓝是整个界面最后一点外来色。
    浅色底用墨（对比最强），深色底用柠檬（深底上唯一亮色）。
    """
    return "#C8F751" if mode == "dark" else "#0B0E14"


